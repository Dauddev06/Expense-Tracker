export type IconName = keyof typeof PATHS;

// Icons are decoration: the text next to them already says what they mean,
// so screen readers skip them (aria-hidden).
export function Icon({ name, className = "size-5" }: { name: IconName; className?: string }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={`shrink-0 ${className}`}
    >
      {PATHS[name]}
    </svg>
  );
}

// An icon inside a soft coloured square, used at the start of list rows and cards.
export function IconTile({
  name,
  tone = "bg-tile text-ink-2",
  size = "md",
}: {
  name: IconName;
  tone?: string; // background + text colour classes
  size?: "sm" | "md" | "lg";
}) {
  const box = size === "sm" ? "size-8 rounded-lg" : size === "lg" ? "size-12 rounded-2xl" : "size-10 rounded-xl";
  const icon = size === "sm" ? "size-4" : size === "lg" ? "size-6" : "size-5";
  return (
    <span className={`inline-flex shrink-0 items-center justify-center ${box} ${tone}`}>
      <Icon name={name} className={icon} />
    </span>
  );
}
